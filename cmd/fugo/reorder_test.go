func TestReorderSkipsComputedRouterKeys(t *testing.T) {
	t.Parallel()

	src := `package ui

func Build(ctx *fugo.Context) fg.Widget {
	key := "/dynamic"

	return fg.Router(map[string]func() fg.Widget{
		"/settings": func() fg.Widget { return settingsPage(ctx) },
		key:         func() fg.Widget { return dynamicPage(ctx) },
		"/about":    func() fg.Widget { return aboutPage(ctx) },
	}, "/")
}
`

	path := filepath.Join(t.TempDir(), "file.go")
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}

	changed, err := reorderFile(path)
	if err != nil {
		t.Fatalf("reorderFile: %v", err)
	}
	if changed {
		t.Error("reorderFile touched a Router map with a computed key")
	}
}
