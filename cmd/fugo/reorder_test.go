func TestReorderDoesNotCrossNonFuncDecl(t *testing.T) {
	t.Parallel()

	// A var block splits the file into two independent func runs; each run
	// reorders on its own (exported before unexported), but funcs must never
	// move across the var boundary into the other run.
	src := `package ui

func b() {
}

func A() {
}

var x = 1

func d() {
}

func C() {
}
`
	want := `package ui

func A() {
}

func b() {
}

var x = 1

func C() {
}

func d() {
}
`
	if got := writeAndReorder(t, src); got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

func TestReorderLeavesAlreadyOrderedFileUntouched(t *testing.T) {
	t.Parallel()

	src := `package ui

func Build() {
}

func Exported() {
}

func helper() {
}
`

	path := filepath.Join(t.TempDir(), "file.go")
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}

	changed, err := reorderFile(path)
	if err != nil {
		t.Fatalf("reorderFile: %v", err)
	}
	if changed {
		t.Error("reorderFile reported a change on an already-ordered file")
	}
}

func TestReorderSkipsGeneratedFiles(t *testing.T) {
	t.Parallel()

	src := `// Code generated by somegen; DO NOT EDIT.
package ui

func b() {
}

func a() {
}
`

	path := filepath.Join(t.TempDir(), "file.go")
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}

	changed, err := reorderFile(path)
	if err != nil {
		t.Fatalf("reorderFile: %v", err)
	}
	if changed {
		t.Error("reorderFile modified a generated file")
	}

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != src {
		t.Errorf("generated file content changed:\n%s", got)
	}
}

