package main

import (
	"os"
	"path/filepath"
	"testing"
)

func writeAndReorder(t *testing.T, src string) string {
	t.Helper()

	path := filepath.Join(t.TempDir(), "file.go")
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}

	if _, err := reorderFile(path); err != nil {
		t.Fatalf("reorderFile: %v", err)
	}

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	return string(got)
}

func TestReorderFuncsEntrypointFirst(t *testing.T) {
	t.Parallel()

	src := `package ui

func aboutPage() {
}

func Build() {
}

func homePage() {
}
`
	want := `package ui

func Build() {
}

func aboutPage() {
}

func homePage() {
}
`
	if got := writeAndReorder(t, src); got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

